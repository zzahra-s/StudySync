-- StudySync schema for Supabase / PostgreSQL.
-- Postgres port of finalizednormalized.sql + add_target_cgpa_tables.sql.
-- Run once in the Supabase SQL Editor, then run seed.sql if you want the sample data.
-- WARNING: this drops and recreates every StudySync table.

DROP TABLE IF EXISTS TargetCGPASemesters CASCADE;
DROP TABLE IF EXISTS TargetCGPAPlan CASCADE;
DROP TABLE IF EXISTS TaskManager CASCADE;
DROP TABLE IF EXISTS CourseMaterialWeightage CASCADE;
DROP TABLE IF EXISTS TopCourses CASCADE;
DROP TABLE IF EXISTS TaskProgress CASCADE;
DROP TABLE IF EXISTS StudyHours CASCADE;
DROP TABLE IF EXISTS StudyPlannerTasks CASCADE;
DROP TABLE IF EXISTS ScenarioCourses CASCADE;
DROP TABLE IF EXISTS GPAScenarios CASCADE;
DROP TABLE IF EXISTS Books CASCADE;
DROP TABLE IF EXISTS CourseMaterials CASCADE;
DROP TABLE IF EXISTS Deadlines CASCADE;
DROP TABLE IF EXISTS Grades CASCADE;
DROP TABLE IF EXISTS Courses CASCADE;
DROP TABLE IF EXISTS Semesters CASCADE;
DROP TABLE IF EXISTS Students CASCADE;
DROP TABLE IF EXISTS GradePoints CASCADE;

-- Timestamps are stored as UTC wall-clock time (same as the SQL Server version).

CREATE TABLE GradePoints (
    letter_grade VARCHAR(2) PRIMARY KEY,
    grade_points DECIMAL(4,2) NOT NULL
);

CREATE TABLE Students (
    student_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(100) NOT NULL,
    roll_number VARCHAR(100) NOT NULL,
    email VARCHAR(100) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    created_at TIMESTAMP DEFAULT timezone('utc', now())
);
-- SQL Server compared emails case-insensitively; keep that guarantee.
CREATE UNIQUE INDEX students_email_lower_key ON Students (LOWER(email));

CREATE TABLE Semesters (
    semester_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id INT NOT NULL,
    semester_name VARCHAR(50) NOT NULL,
    start_date DATE,
    end_date DATE,
    FOREIGN KEY (student_id) REFERENCES Students(student_id) ON DELETE CASCADE,
    UNIQUE (student_id, semester_name)
);

CREATE TABLE Courses (
    course_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    semester_id INT NOT NULL,
    course_code VARCHAR(20) NOT NULL,
    course_name VARCHAR(100) NOT NULL,
    credit_hours DECIMAL(3,1) NOT NULL CHECK (credit_hours > 0),
    instructor_name VARCHAR(100),
    FOREIGN KEY (semester_id) REFERENCES Semesters(semester_id) ON DELETE CASCADE,
    UNIQUE (semester_id, course_code)
);

CREATE TABLE Grades (
    grade_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id INT NOT NULL UNIQUE,
    letter_grade VARCHAR(2) NOT NULL,
    comments VARCHAR(500),
    FOREIGN KEY (course_id) REFERENCES Courses(course_id) ON DELETE CASCADE,
    FOREIGN KEY (letter_grade) REFERENCES GradePoints(letter_grade)
);

-- status/priority checks are case-insensitive, as they were under SQL Server's default collation.
CREATE TABLE Deadlines (
    deadline_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id INT NOT NULL,
    title VARCHAR(150) NOT NULL,
    due_date TIMESTAMP NOT NULL,
    status VARCHAR(10) DEFAULT 'Pending' CHECK (LOWER(status) IN ('pending', 'completed')),
    priority VARCHAR(10) DEFAULT 'Medium' CHECK (LOWER(priority) IN ('high', 'medium', 'low')),
    allocated_study_hours DECIMAL(4,1) DEFAULT 0,
    description VARCHAR(500) NULL,
    FOREIGN KEY (course_id) REFERENCES Courses(course_id) ON DELETE CASCADE
);

CREATE TABLE CourseMaterials (
    material_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id INT NOT NULL,
    student_id INT NULL,
    material_name VARCHAR(255) NOT NULL,
    file_path VARCHAR(500),
    description TEXT NULL,
    uploaded_at TIMESTAMP DEFAULT timezone('utc', now()),
    FOREIGN KEY (course_id) REFERENCES Courses(course_id) ON DELETE CASCADE,
    FOREIGN KEY (student_id) REFERENCES Students(student_id) ON DELETE SET NULL
);

CREATE TABLE Books (
    book_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id INT NOT NULL,
    title VARCHAR(255) NOT NULL,
    author VARCHAR(200),
    isbn VARCHAR(20),
    description VARCHAR(600) NULL,
    pdf_link VARCHAR(500) NULL,
    FOREIGN KEY (course_id) REFERENCES Courses(course_id) ON DELETE CASCADE
);

CREATE TABLE GPAScenarios (
    scenario_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id INT NOT NULL,
    scenario_name VARCHAR(100) NOT NULL,
    created_at TIMESTAMP DEFAULT timezone('utc', now()),
    FOREIGN KEY (student_id) REFERENCES Students(student_id) ON DELETE CASCADE
);

CREATE TABLE ScenarioCourses (
    scenario_id INT NOT NULL,
    course_id INT NOT NULL,
    expected_grade VARCHAR(2) NOT NULL,
    PRIMARY KEY (scenario_id, course_id),
    FOREIGN KEY (scenario_id) REFERENCES GPAScenarios(scenario_id) ON DELETE CASCADE,
    FOREIGN KEY (course_id) REFERENCES Courses(course_id) ON DELETE CASCADE,
    FOREIGN KEY (expected_grade) REFERENCES GradePoints(letter_grade)
);

CREATE TABLE StudyPlannerTasks (
    task_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id INT NOT NULL,
    course_id INT NULL,
    title VARCHAR(255) NOT NULL,
    due_date DATE,
    description TEXT,
    status VARCHAR(20) DEFAULT 'pending',
    created_at TIMESTAMP DEFAULT timezone('utc', now()),
    FOREIGN KEY (student_id) REFERENCES Students(student_id) ON DELETE CASCADE,
    FOREIGN KEY (course_id) REFERENCES Courses(course_id) ON DELETE SET NULL
);

CREATE TABLE StudyHours (
    hour_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id INT NOT NULL,
    course_id INT NULL,
    date DATE NOT NULL,
    hours DECIMAL(4,2) NOT NULL,
    created_at TIMESTAMP DEFAULT timezone('utc', now()),
    FOREIGN KEY (student_id) REFERENCES Students(student_id) ON DELETE CASCADE,
    FOREIGN KEY (course_id) REFERENCES Courses(course_id) ON DELETE SET NULL
);

CREATE TABLE TaskProgress (
    progress_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id INT NOT NULL,
    total_tasks INT DEFAULT 0,
    completed_tasks INT DEFAULT 0,
    updated_at TIMESTAMP DEFAULT timezone('utc', now()),
    FOREIGN KEY (student_id) REFERENCES Students(student_id) ON DELETE CASCADE,
    UNIQUE (student_id)
);

CREATE TABLE TopCourses (
    top_course_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id INT NOT NULL,
    course_id INT,
    created_at TIMESTAMP DEFAULT timezone('utc', now()),
    FOREIGN KEY (student_id) REFERENCES Students(student_id) ON DELETE CASCADE,
    FOREIGN KEY (course_id) REFERENCES Courses(course_id) ON DELETE CASCADE
);

CREATE TABLE CourseMaterialWeightage (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id INT NOT NULL UNIQUE,
    quizzes_percentage INT NOT NULL CHECK (quizzes_percentage BETWEEN 0 AND 100),
    assignments_percentage INT NOT NULL CHECK (assignments_percentage BETWEEN 0 AND 100),
    midterm_percentage INT NOT NULL CHECK (midterm_percentage BETWEEN 0 AND 100),
    final_percentage INT NOT NULL CHECK (final_percentage BETWEEN 0 AND 100),
    updated_at TIMESTAMP DEFAULT timezone('utc', now()),
    FOREIGN KEY (course_id) REFERENCES Courses(course_id) ON DELETE CASCADE
);

CREATE TABLE TaskManager (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INT NOT NULL,
    course_id INT NOT NULL,
    title VARCHAR(255) NOT NULL,
    status VARCHAR(10) NOT NULL CHECK (status IN ('todo', 'done')),
    linked_deadline_id INT NULL,
    created_at TIMESTAMP DEFAULT timezone('utc', now()),
    FOREIGN KEY (user_id) REFERENCES Students(student_id) ON DELETE CASCADE,
    FOREIGN KEY (course_id) REFERENCES Courses(course_id) ON DELETE CASCADE,
    FOREIGN KEY (linked_deadline_id) REFERENCES Deadlines(deadline_id) ON DELETE SET NULL
);

CREATE TABLE TargetCGPAPlan (
    plan_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id INT NOT NULL,
    current_cgpa DECIMAL(4,2) NOT NULL,
    target_cgpa DECIMAL(4,2) NOT NULL,
    remaining_credits INT NOT NULL,
    remaining_semesters INT NOT NULL,
    total_degree_credits INT NOT NULL DEFAULT 120,
    distribution_method VARCHAR(20) NOT NULL CHECK (distribution_method IN ('equal', 'custom')),
    is_achievable BOOLEAN NOT NULL DEFAULT TRUE,
    required_sgpa DECIMAL(4,2) NULL,
    max_possible_cgpa DECIMAL(4,2) NULL,
    created_at TIMESTAMP DEFAULT timezone('utc', now()),
    updated_at TIMESTAMP DEFAULT timezone('utc', now()),
    FOREIGN KEY (student_id) REFERENCES Students(student_id) ON DELETE CASCADE
);

CREATE TABLE TargetCGPASemesters (
    semester_plan_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_id INT NOT NULL,
    semester_number INT NOT NULL,
    semester_name VARCHAR(100) NOT NULL,
    credits INT NOT NULL,
    required_sgpa DECIMAL(4,2) NOT NULL,
    is_achievable BOOLEAN NOT NULL DEFAULT TRUE,
    FOREIGN KEY (plan_id) REFERENCES TargetCGPAPlan(plan_id) ON DELETE CASCADE,
    UNIQUE (plan_id, semester_number)
);

CREATE INDEX idx_student_target_cgpa ON TargetCGPAPlan(student_id);
CREATE INDEX idx_plan_semesters ON TargetCGPASemesters(plan_id);

